using canclaimsextended.src.auxiliary;
using Vintagestory.API.Common;
using Vintagestory.API.Common.CommandAbbr;
using Vintagestory.API.Server;
using static canclaimsextended.src.commands.register.ServerCommands;

namespace canclaimsextended.src.commands.register
{
    static class CadminCommandsRegistrar
    {
        public static void Register(ICoreServerAPI sapi, CommandArgumentParsers parsers, string name)
        {
            // Once, on the root: the game checks a command's preconditions before it passes the call
            // on to a subcommand, so nothing under /cadmin runs for a player without the admin role.
            sapi.ChatCommands.Create(name)
                .RequiresPlayer().RequiresPrivilege(Privilege.chat)
                .WithPreCondition(BaseCommand.RequireAdminRole)
                .BeginSub("city")
                    .BeginSub("delete").WithDesc(D("cadmin-city-delete"))
                        .WithArgs(parsers.Word("cityName")).HandleWith(CAdminCommand.CityDelete).EndSub()
                    .BeginSub("create").WithDesc(D("cadmin-city-create"))
                        .WithArgs(parsers.Word("cityName"), parsers.OptionalWord("mayorName")).HandleWith(CAdminCommand.CityCreate).EndSub()
                    .BeginSub("claim").WithDesc(D("cadmin-city-claim"))
                        .WithArgs(parsers.Word("cityName")).HandleWith(CAdminCommand.CityClaim).EndSub()
                    .BeginSub("unclaim").WithDesc(D("cadmin-city-unclaim"))
                        .WithArgs(parsers.Word("cityName")).HandleWith(CAdminCommand.CityUnclaim).EndSub()
                    .BeginSub("bonuschunks")
                        .WithArgs(parsers.Word("cityName"), parsers.Int("amount")).HandleWith(CAdminCommand.CityBonusChunks).EndSub()
                    .BeginSub("setmayor")
                        .WithArgs(parsers.Word("cityName"), parsers.Word("playerName")).HandleWith(CAdminCommand.CitySetMayor).EndSub()
                    .BeginSub("bonusplots")
                        .WithArgs(parsers.Word("cityName"), parsers.Int("amount")).HandleWith(CAdminCommand.CityBonusPlots).EndSub()
                    .BeginSub("setdefault").WithDesc(D("cadmin-city-setdefault"))
                        .WithArgs(parsers.OptionalWord("cityName")).HandleWith(CAdminCommand.CitySetDefault).EndSub()
                    .BeginSub("technical").WithDesc(D("cadmin-city-technical"))
                        .WithArgs(parsers.Word("cityName"), OnOff(parsers)).HandleWith(CAdminCommand.CityTechnical).EndSub()
                .EndSub()
                .BeginSub("plot")
                    .BeginSub("info").WithAlias("dump").WithDesc(D("cadmin-plot-info"))
                        .HandleWith(CAdminCommand.PlotInfo).EndSub()
                    .BeginSub("create").WithDesc(D("cadmin-plot-create"))
                        .WithArgs(parsers.Word("cityName")).HandleWith(CAdminPlotCommand.Create).EndSub()
                    .BeginSub("extend").WithDesc(D("cadmin-plot-extend"))
                        .HandleWith(CAdminPlotCommand.Extend).EndSub()
                    .BeginSub("delete").WithDesc(D("cadmin-plot-delete"))
                        .HandleWith(CAdminPlotCommand.Delete).EndSub()
                    .BeginSub("cut").WithDesc(D("cadmin-plot-cut"))
                        .WithArgs(parsers.OptionalInt("part"))
                        .HandleWith(CAdminPlotCommand.Cut).EndSub()
                    .BeginSub("grow").WithDesc(D("cadmin-plot-grow"))
                        .WithArgs(parsers.WordRange("direction", Codes.Directions), parsers.Int("blocks")).HandleWith(args => CAdminPlotCommand.Resize(args, "grow")).EndSub()
                    .BeginSub("shrink").WithDesc(D("cadmin-plot-shrink"))
                        .WithArgs(parsers.WordRange("direction", Codes.Directions), parsers.Int("blocks")).HandleWith(args => CAdminPlotCommand.Resize(args, "shrink")).EndSub()
                    .BeginSub("type").WithDesc(D("cadmin-plot-type"))
                        .WithArgs(parsers.Word("type")).HandleWith(CAdminPlotCommand.SetType).EndSub()
                    .BeginSub("name").WithDesc(D("cadmin-plot-name"))
                        .WithArgs(parsers.OptionalWord("name")).HandleWith(CAdminPlotCommand.SetName).EndSub()
                    .BeginSub("perm").WithDesc(D("cadmin-plot-perm"))
                        .WithArgs(parsers.WordRange("group", Codes.PermGroups), parsers.WordRange("type", Codes.PermTypes), OnOff(parsers))
                        .HandleWith(CAdminPlotCommand.SetPerm).EndSub()
                    .BeginSub("flag").WithDesc(D("cadmin-plot-flag"))
                        .WithArgs(parsers.WordRange("flag", Codes.Flags), OnOff(parsers))
                        .HandleWith(CAdminPlotCommand.SetFlag).EndSub()
                    .BeginSub("fee").WithDesc(D("cadmin-plot-fee"))
                        .WithArgs(parsers.Int("amount")).HandleWith(CAdminPlotCommand.SetFee).EndSub()
                    .BeginSub("sell").WithDesc(D("cadmin-plot-sell"))
                        .WithArgs(parsers.Int("price")).HandleWith(CAdminPlotCommand.Sell).EndSub()
                    .BeginSub("nosell").WithDesc(D("cadmin-plot-nosell"))
                        .HandleWith(CAdminPlotCommand.NoSell).EndSub()
                    .BeginSub("owner").WithDesc(D("cadmin-plot-owner"))
                        .WithArgs(parsers.Word("playerName")).HandleWith(CAdminPlotCommand.SetOwner).EndSub()
                    .BeginSub("takeback").WithDesc(D("cadmin-plot-takeback"))
                        .HandleWith(CAdminPlotCommand.TakeBack).EndSub()
                .EndSub()
                .BeginSub("player")
                    .BeginSub("info")
                        .WithArgs(parsers.Word("playerName")).HandleWith(CAdminCommand.PlayerInfoCmd).EndSub()
                    .BeginSub("kick").WithDesc(D("cadmin-player-kick"))
                        .WithArgs(parsers.Word("playerName")).HandleWith(CAdminCommand.PlayerKick).EndSub()
                    .BeginSub("joindefault").WithDesc(D("cadmin-player-joindefault"))
                        .WithArgs(parsers.OptionalWord("playerName")).HandleWith(CAdminCommand.PlayerJoinDefault).EndSub()
                    .BeginSub("jail").WithDesc(D("cadmin-player-jail"))
                        .WithArgs(parsers.Word("playerName"), parsers.Word("cityName"), parsers.OptionalInt("minutes"))
                        .HandleWith(CAdminCommand.PlayerJail).EndSub()
                    .BeginSub("release").WithDesc(D("cadmin-player-release"))
                        .WithArgs(parsers.Word("playerName")).HandleWith(CAdminCommand.PlayerRelease).EndSub()
                .EndSub()
                .BeginSub("world")
                    .BeginSub("info").HandleWith(CAdminCommand.WorldInfoCmd).EndSub()
                    .BeginSub("set").WithDesc(D("cadmin-world-set"))
                        .WithArgs(parsers.WordRange("flag", part.structure.WorldInfo.Codes), OnOff(parsers))
                        .HandleWith(CAdminCommand.WorldSet).EndSub()
                .EndSub()
                .BeginSub("reload").WithDesc(D("cadmin-reload"))
                    .HandleWith(CAdminCommand.Reload).EndSub()
                .BeginSub("backup").WithDesc(D("cadmin-backup"))
                    .HandleWith(CAdminCommand.Backup).EndSub()
                .BeginSub("day").WithDesc(D("cadmin-day"))
                    .HandleWith(CAdminCommand.Day).EndSub()
                .BeginSub("setcfg").WithDesc(D("cadmin-setcfg"))
                    .WithArgs(parsers.Word("key"), parsers.Word("value")).HandleWith(CAdminCommand.SetCfg).EndSub()
                .BeginSub("getcfg").WithDesc(D("cadmin-getcfg"))
                    .HandleWith(CAdminCommand.GetCfg).EndSub()
                .BeginSub("as").WithDesc(D("cadmin-as"))
                    .WithArgs(parsers.Word("cityName"), parsers.All("command")).HandleWith(CAdminCommand.ActAs).EndSub()
                .BeginSub("blockrule").WithDesc(D("cadmin-blockrule"))
                    .BeginSub("list").HandleWith(CAdminCommand.BlockRuleList).EndSub()
                    .BeginSub("hand").WithDesc(D("cadmin-blockrule-hand"))
                        .HandleWith(CAdminCommand.BlockRuleHand).EndSub()
                    .BeginSub("add").WithDesc(D("cadmin-blockrule-add"))
                        .WithArgs(parsers.Word("key"), parsers.Word("plotType")).HandleWith(CAdminCommand.BlockRuleAdd).EndSub()
                    .BeginSub("remove").WithDesc(D("cadmin-blockrule-remove"))
                        .WithArgs(parsers.Word("key"), parsers.OptionalWord("plotType")).HandleWith(CAdminCommand.BlockRuleRemove).EndSub()
                .EndSub()
                .BeginSub("level").WithDesc(D("cadmin-level"))
                    .BeginSub("list").HandleWith(CAdminCommand.LevelList).EndSub()
                    .BeginSub("add").WithDesc(D("cadmin-level-add"))
                        .WithArgs(parsers.Int("citizens")).HandleWith(CAdminCommand.LevelAdd).EndSub()
                    .BeginSub("remove")
                        .WithArgs(parsers.Int("citizens")).HandleWith(CAdminCommand.LevelRemove).EndSub()
                    .BeginSub("set").WithDesc(D("cadmin-level-set"))
                        .WithArgs(parsers.Int("citizens"), parsers.WordRange("field", Settings.LevelFields), parsers.Word("value"))
                        .HandleWith(CAdminCommand.LevelSet).EndSub()
                .EndSub();
        }
    }
}
