using canclaimsextended.src.auxiliary;
using canclaimsextended.src.rights;
using Vintagestory.API.Common;
using Vintagestory.API.Common.CommandAbbr;
using Vintagestory.API.Server;
using static canclaimsextended.src.commands.register.ServerCommands;

namespace canclaimsextended.src.commands.register
{
    /// <summary>/plot and everything under it.</summary>
    static class PlotCommandsRegistrar
    {
        public static void Register(ICoreServerAPI sapi, CommandArgumentParsers parsers, string name)
        {
            sapi.ChatCommands.Create(name)
                .RequiresPlayer().RequiresPrivilege(Privilege.chat)
                .BeginSub("here")
                    .WithDesc(D("plot-here"))
                    .HandleWith(PlotCommand.HereInfo)
                .EndSub()
                .BeginSub("fs")
                    .WithDesc(D("plot-fs"))
                    .WithPreCondition(args => BaseCommand.RequirePermission(args, EnumPlayerPermissions.PLOT_SET_FS))
                    .WithArgs(parsers.Int("price"))
                    .HandleWith(PlotCommandOwnership.SetForSale)
                .EndSub()
                .BeginSub("nfs")
                    .WithDesc(D("plot-nfs"))
                    .WithPreCondition(args => BaseCommand.RequirePermission(args, EnumPlayerPermissions.PLOT_SET_NFS))
                    .HandleWith(PlotCommandOwnership.SetNotForSale)
                .EndSub()
                .BeginSub("claim")
                    .WithDesc(D("plot-claim"))
                    .WithPreCondition(args => BaseCommand.RequirePermission(args, EnumPlayerPermissions.PLOT_CLAIM))
                    .WithArgs(parsers.OptionalInt("price"))
                    .HandleWith(PlotCommandOwnership.Claim)
                .EndSub()
                .BeginSub("unclaim")
                    .WithDesc(D("plot-unclaim"))
                    .WithPreCondition(args => BaseCommand.RequirePermission(args, EnumPlayerPermissions.PLOT_UNCLAIM))
                    .HandleWith(PlotCommandOwnership.Unclaim)
                .EndSub()
                .BeginSub("create")
                    .WithDesc(D("plot-create"))
                    .WithArgs(parsers.OptionalWord("name"))
                    .HandleWith(PlotCommandShape.Create)
                .EndSub()
                .BeginSub("delete")
                    .WithDesc(D("plot-delete"))
                    .HandleWith(PlotCommandShape.Delete)
                .EndSub()
                .BeginSub("extend")
                    .WithDesc(D("plot-extend"))
                    .WithArgs(parsers.OptionalWord("plot"))
                    .HandleWith(PlotCommandShape.Extend)
                .EndSub()
                .BeginSub("grow")
                    .WithDesc(D("plot-grow"))
                    .WithArgs(parsers.WordRange("direction", Codes.Directions), parsers.Int("blocks"))
                    .HandleWith(args => PlotCommandShape.Resize(args, 1))
                .EndSub()
                .BeginSub("shrink")
                    .WithDesc(D("plot-shrink"))
                    .WithArgs(parsers.WordRange("direction", Codes.Directions), parsers.Int("blocks"))
                    .HandleWith(args => PlotCommandShape.Resize(args, -1))
                .EndSub()
                .BeginSub("cut")
                    .WithDesc(D("plot-cut"))
                    .WithArgs(parsers.OptionalWord("plot"), parsers.OptionalInt("part"))
                    .HandleWith(PlotCommandShape.Cut)
                .EndSub()
                .BeginSub("boxes")
                    .WithDesc(D("plot-boxes"))
                    .HandleWith(PlotCommandShape.Boxes)
                .EndSub()
                .BeginSub("types").WithDesc(D("plot-types")).HandleWith(PlotCommandType.ListTypes).EndSub()
                .BeginSub("set")
                    .WithDesc(D("plot-set"))
                    .BeginSub("type").WithDesc(D("plot-set-type"))
                        .WithArgs(parsers.Word("type")).HandleWith(PlotCommandType.SetType).EndSub()
                    .BeginSub("perm").WithAlias("p")
                        .WithArgs(parsers.WordRange("group", Codes.PermGroups), parsers.WordRange("type", Codes.PermTypes), OnOff(parsers))
                        .HandleWith(PlotCommandSettings.SetPerm)
                    .EndSub()
                    .BeginSub("pvp").WithArgs(OnOff(parsers)).HandleWith(a => PlotCommandSettings.SetFlag(a, "pvp")).EndSub()
                    .BeginSub("fire").WithArgs(OnOff(parsers)).HandleWith(a => PlotCommandSettings.SetFlag(a, "fire")).EndSub()
                    .BeginSub("blast").WithArgs(OnOff(parsers)).HandleWith(a => PlotCommandSettings.SetFlag(a, "blast")).EndSub()
                    .BeginSub("nomobspawn").WithArgs(OnOff(parsers)).HandleWith(a => PlotCommandSettings.SetFlag(a, "nomobspawn")).EndSub()
                    .BeginSub("name").WithDesc(D("plot-set-name")).WithArgs(parsers.OptionalWord("name")).HandleWith(PlotCommandSettings.SetName).EndSub()
                    .BeginSub("fee").WithDesc(D("plot-set-fee")).WithArgs(parsers.Int("amount")).HandleWith(PlotCommandFee.SetFee).EndSub()
                .EndSub();
        }
    }
}
