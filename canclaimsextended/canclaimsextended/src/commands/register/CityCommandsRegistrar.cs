using canclaimsextended.src.auxiliary;
using canclaimsextended.src.rights;
using Vintagestory.API.Common;
using Vintagestory.API.Common.CommandAbbr;
using Vintagestory.API.Server;
using static canclaimsextended.src.commands.register.ServerCommands;

namespace canclaimsextended.src.commands.register
{
    /// <summary>/city and everything under it.</summary>
    static class CityCommandsRegistrar
    {
        public static void Register(ICoreServerAPI sapi, CommandArgumentParsers parsers, string name)
        {
            IChatCommand city = sapi.ChatCommands.Create(name)
                .RequiresPlayer().RequiresPrivilege(Privilege.chat);
            city
                .BeginSub("create")
                    .WithAlias("new")
                    .WithDesc(D("city-create"))
                    .WithArgs(parsers.Word("cityName"))
                    .HandleWith(CityCommand.CreateNewCity)
                .EndSub()
                .BeginSub("delete")
                    .WithDesc(D("city-delete"))
                    .WithArgs(parsers.OptionalWord("cityName"))
                    .HandleWith(CityCommand.DeleteCity)
                .EndSub()
                .BeginSub("claim")
                    .WithDesc(D("city-claim"))
                    .WithPreCondition(args => BaseCommand.RequirePermission(args, EnumPlayerPermissions.CITY_CLAIM_CHUNK))
                    .HandleWith(CityCommand.ClaimChunk)
                .EndSub()
                .BeginSub("unclaim")
                    .WithDesc(D("city-unclaim"))
                    .WithPreCondition(args => BaseCommand.RequirePermission(args, EnumPlayerPermissions.CITY_UNCLAIM_CHUNK))
                    .HandleWith(CityCommand.UnclaimChunk)
                .EndSub()
                .BeginSub("here")
                    .WithDesc(D("city-here"))
                    .WithPreCondition(args => BaseCommand.RequirePermission(args, EnumPlayerPermissions.CITY_HERE))
                    .HandleWith(CityCommand.CityHere)
                .EndSub()
                .BeginSub("info")
                    .WithDesc(D("city-info"))
                    .WithPreCondition(args => BaseCommand.RequirePermission(args, EnumPlayerPermissions.CITY_INFO))
                    .WithArgs(parsers.OptionalWord("cityName"))
                    .HandleWith(CityCommand.CityInfo)
                .EndSub()
                .BeginSub("list")
                    .WithDesc(D("city-list"))
                    .HandleWith(CityCommand.ListCities)
                .EndSub()
                .BeginSub("invite")
                    .WithDesc(D("city-invite"))
                    .WithPreCondition(args => BaseCommand.RequirePermission(args, EnumPlayerPermissions.CITY_INVITE))
                    .WithArgs(parsers.Word("playerName"))
                    .HandleWith(CityCommandMembers.Invite)
                .EndSub()
                .BeginSub("uninvite")
                    .WithDesc(D("city-uninvite"))
                    .WithPreCondition(args => BaseCommand.RequirePermission(args, EnumPlayerPermissions.CITY_UNINVITE))
                    .WithArgs(parsers.Word("playerName"))
                    .HandleWith(CityCommandMembers.Uninvite)
                .EndSub()
                .BeginSub("join")
                    .WithDesc(D("city-join"))
                    .WithArgs(parsers.Word("cityName"))
                    .HandleWith(CityCommandMembers.Join)
                .EndSub()
                .BeginSub("deny")
                    .WithDesc(D("city-deny"))
                    .WithArgs(parsers.Word("cityName"))
                    .HandleWith(CityCommandMembers.Deny)
                .EndSub()
                .BeginSub("leave")
                    .WithDesc(D("city-leave"))
                    .HandleWith(CityCommandMembers.Leave)
                .EndSub()
                .BeginSub("kick")
                    .WithDesc(D("city-kick"))
                    .WithPreCondition(args => BaseCommand.RequirePermission(args, EnumPlayerPermissions.CITY_KICK))
                    .WithArgs(parsers.Word("playerName"))
                    .HandleWith(CityCommandMembers.Kick)
                .EndSub()
                .BeginSub("invites")
                    .WithDesc(D("city-invites"))
                    .HandleWith(CityCommandMembers.Invites)
                .EndSub()
                .BeginSub("rank")
                    .WithDesc(D("city-rank"))
                    .HandleWith(CityCommandRanks.List)
                    .BeginSub("list").WithDesc(D("city-rank-list")).HandleWith(CityCommandRanks.List).EndSub()
                    .BeginSub("info").WithArgs(parsers.Word("rankName")).HandleWith(CityCommandRanks.Info).EndSub()
                    .BeginSub("create").WithArgs(parsers.Word("rankName")).HandleWith(CityCommandRanks.Create).EndSub()
                    .BeginSub("delete").WithArgs(parsers.Word("rankName")).HandleWith(CityCommandRanks.Delete).EndSub()
                    .BeginSub("addperm").WithArgs(parsers.Word("rankName"), parsers.Word("permission")).HandleWith(CityCommandRanks.AddPerm).EndSub()
                    .BeginSub("removeperm").WithArgs(parsers.Word("rankName"), parsers.Word("permission")).HandleWith(CityCommandRanks.RemovePerm).EndSub()
                    .BeginSub("grant").WithArgs(parsers.Word("rankName"), parsers.Word("playerName")).HandleWith(CityCommandRanks.Grant).EndSub()
                    .BeginSub("revoke").WithArgs(parsers.Word("rankName"), parsers.Word("playerName")).HandleWith(CityCommandRanks.Revoke).EndSub()
                .EndSub()
                .BeginSub("criminal")
                    .WithDesc(D("city-criminal"))
                    .HandleWith(CityCommandPrison.CriminalList)
                    .BeginSub("add").WithArgs(parsers.Word("playerName")).HandleWith(CityCommandPrison.CriminalAdd).EndSub()
                    .BeginSub("remove").WithArgs(parsers.Word("playerName")).HandleWith(CityCommandPrison.CriminalRemove).EndSub()
                    .BeginSub("list").HandleWith(CityCommandPrison.CriminalList).EndSub()
                .EndSub()
                .BeginSub("prison")
                    .WithDesc(D("city-prison"))
                    .HandleWith(CityCommandPrison.ListPrisons)
                    .BeginSub("addcell").WithDesc(D("city-prison-addcell")).HandleWith(CityCommandPrison.AddCell).EndSub()
                    .BeginSub("removecell").WithDesc(D("city-prison-removecell")).HandleWith(CityCommandPrison.RemoveCell).EndSub()
                    .BeginSub("list").HandleWith(CityCommandPrison.ListPrisons).EndSub()
                .EndSub()
                .BeginSub("summon")
                    .WithDesc(D("city-summon"))
                    .HandleWith(CityCommandSummon.List)
                    .BeginSub("list").HandleWith(CityCommandSummon.List).EndSub()
                    .BeginSub("set").WithDesc(D("city-summon-set"))
                        .WithArgs(parsers.OptionalWord("name")).HandleWith(CityCommandSummon.Set).EndSub()
                    .BeginSub("tp").WithDesc(D("city-summon-tp"))
                        .WithArgs(parsers.Word("point")).HandleWith(CityCommandSummon.Teleport).EndSub()
                    .BeginSub("cancel").HandleWith(CityCommandSummon.CancelTeleport).EndSub()
                .EndSub()
                // The right (or being the mayor) is checked by the handler.
                .BeginSub("outpost")
                    .WithDesc(D("city-outpost"))
                    .HandleWith(CityCommandPlotsExtra.ClaimOutpost)
                .EndSub()
                .BeginSub("extraclaim")
                    .WithDesc(D("city-extraclaim"))
                    .HandleWith(CityCommandPlotsExtra.ClaimExtraChunk)
                .EndSub();
            AddPlotsGroup(city, parsers);
            city
                .BeginSub("log").WithDesc(D("city-log")).WithArgs(parsers.OptionalInt("page")).HandleWith(CityCommandLog.Show).EndSub()
                .BeginSub("balance").WithDesc(D("city-balance")).HandleWith(CityCommandMoney.Balance).EndSub()
                .BeginSub("prices").WithDesc(D("city-prices")).HandleWith(CityCommandMoney.Prices).EndSub();
            AddSettings(city, parsers);
            AddSelection(city, parsers);
        }

        /// <summary>The rights of a group are checked by each handler: the mayor, or the right of that subcommand.</summary>
        static void AddPlotsGroup(IChatCommand city, CommandArgumentParsers parsers)
        {
            city
                .BeginSub("plotsgroup")
                    .WithAlias("pg")
                    .WithDesc(D("city-pg"))
                    .BeginSub("create").WithArgs(parsers.Word("groupName")).HandleWith(CityCommandPlotsGroup.Create).EndSub()
                    .BeginSub("delete").WithArgs(parsers.Word("groupName")).HandleWith(CityCommandPlotsGroup.Delete).EndSub()
                    .BeginSub("list").HandleWith(CityCommandPlotsGroup.List).EndSub()
                    .BeginSub("info").WithArgs(parsers.Word("groupName")).HandleWith(CityCommandPlotsGroup.Info).EndSub()
                    .BeginSub("addplot").WithDesc(D("city-pg-addplot")).WithArgs(parsers.Word("groupName"))
                        .HandleWith(CityCommandPlotsGroup.AddPlot).EndSub()
                    .BeginSub("removeplot").WithDesc(D("city-pg-removeplot"))
                        .HandleWith(CityCommandPlotsGroup.RemovePlot).EndSub()
                    .BeginSub("addchunk").WithDesc(D("city-pg-addchunk")).WithArgs(parsers.Word("groupName"))
                        .HandleWith(CityCommandPlotsGroup.AddChunk).EndSub()
                    .BeginSub("removechunk").WithDesc(D("city-pg-removechunk"))
                        .HandleWith(CityCommandPlotsGroup.RemoveChunk).EndSub()
                    .BeginSub("invite").WithArgs(parsers.Word("groupName"), parsers.Word("playerName"))
                        .HandleWith(CityCommandPlotsGroup.Invite).EndSub()
                    .BeginSub("uninvite").WithArgs(parsers.Word("groupName"), parsers.Word("playerName"))
                        .HandleWith(CityCommandPlotsGroup.Uninvite).EndSub()
                    .BeginSub("join").WithArgs(parsers.Word("groupName")).HandleWith(CityCommandPlotsGroup.Join).EndSub()
                    .BeginSub("deny").WithArgs(parsers.Word("groupName")).HandleWith(CityCommandPlotsGroup.Deny).EndSub()
                    .BeginSub("kick").WithArgs(parsers.Word("groupName"), parsers.Word("playerName"))
                        .HandleWith(CityCommandPlotsGroup.Kick).EndSub()
                    .BeginSub("leave").WithArgs(parsers.Word("groupName")).HandleWith(CityCommandPlotsGroup.Leave).EndSub()
                    .BeginSub("acceptfee").WithDesc(D("city-pg-acceptfee")).WithArgs(parsers.Word("groupName"))
                        .HandleWith(CityCommandPlotsGroup.AcceptFee).EndSub()
                    .BeginSub("set")
                        .BeginSub("perm").WithArgs(parsers.Word("groupName"), parsers.WordRange("type", Codes.PermTypes), parsers.Bool("value", "on"))
                            .HandleWith(CityCommandPlotsGroup.SetPerm).EndSub()
                        .BeginSub("flag").WithArgs(parsers.Word("groupName"), parsers.WordRange("flag", Codes.Flags), parsers.Bool("value", "on"))
                            .HandleWith(CityCommandPlotsGroup.SetFlag).EndSub()
                        .BeginSub("fee").WithArgs(parsers.Word("groupName"), parsers.Double("amount"))
                            .HandleWith(CityCommandPlotsGroup.SetFee).EndSub()
                    .EndSub()
                .EndSub();
        }

        static void AddSettings(IChatCommand city, CommandArgumentParsers parsers)
        {
            city
                .BeginSub("set")
                    .WithDesc(D("city-set"))
                    .HandleWith(CityCommandSettings.Info)
                    .BeginSub("info").WithDesc(D("city-set-info")).HandleWith(CityCommandSettings.Info).EndSub()
                    .BeginSub("perm").WithAlias("p")
                        .WithDesc(D("city-set-perm"))
                        .WithArgs(parsers.WordRange("group", Codes.PermGroups), parsers.WordRange("type", Codes.PermTypes), OnOff(parsers))
                        .HandleWith(CityCommandSettings.SetPerm)
                    .EndSub()
                    .BeginSub("pvp").WithArgs(OnOff(parsers)).HandleWith(a => CityCommandSettings.SetFlag(a, "pvp", EnumPlayerPermissions.CITY_SET_PVP)).EndSub()
                    .BeginSub("fire").WithArgs(OnOff(parsers)).HandleWith(a => CityCommandSettings.SetFlag(a, "fire", EnumPlayerPermissions.CITY_SET_FIRE)).EndSub()
                    .BeginSub("blast").WithArgs(OnOff(parsers)).HandleWith(a => CityCommandSettings.SetFlag(a, "blast", EnumPlayerPermissions.CITY_SET_BLAST)).EndSub()
                    .BeginSub("nomobspawn").WithArgs(OnOff(parsers)).HandleWith(a => CityCommandSettings.SetFlag(a, "nomobspawn", EnumPlayerPermissions.CITY_SET_MOBSPAWN)).EndSub()
                    .BeginSub("open").WithDesc(D("city-set-open")).WithArgs(OnOff(parsers)).HandleWith(CityCommandSettings.SetOpen).EndSub()
                    .BeginSub("invmsg").WithDesc(D("city-set-invmsg")).WithArgs(parsers.OptionalAll("text")).HandleWith(CityCommandSettings.SetInvMsg).EndSub()
                    .BeginSub("fee").WithDesc(D("city-set-fee")).WithArgs(parsers.Int("amount")).HandleWith(CityCommandSettings.SetFee).EndSub()
                    .BeginSub("name").WithDesc(D("city-set-name")).WithArgs(parsers.Word("newName")).HandleWith(CityCommandIdentity.SetName).EndSub()
                    .BeginSub("color").WithDesc(D("city-set-color")).WithArgs(parsers.Word("color")).HandleWith(CityCommandIdentity.SetColor).EndSub()
                    .BeginSub("dailymsg").WithDesc(D("city-set-dailymsg")).WithArgs(parsers.OptionalAll("text")).HandleWith(CityCommandIdentity.SetDailyMsg).EndSub()
                    .BeginSub("prefix").WithDesc(D("city-set-prefix"))
                        .WithArgs(parsers.Word("playerName"), parsers.OptionalAll("title")).HandleWith(CityCommandIdentity.SetPrefix).EndSub()
                    .BeginSub("aftername").WithDesc(D("city-set-aftername"))
                        .WithArgs(parsers.Word("playerName"), parsers.OptionalAll("title")).HandleWith(CityCommandIdentity.SetAfterName).EndSub()
                    .BeginSub("emblem").WithDesc(D("city-set-emblem"))
                        .WithArgs(parsers.OptionalAll("layers")).HandleWith(CityCommandEmblem.SetEmblem).EndSub()
                .EndSub();
        }

        /// <summary>Borders, the wand and the box selection used to claim plots.</summary>
        static void AddSelection(IChatCommand city, CommandArgumentParsers parsers)
        {
            city
                .BeginSub("borders")
                    .WithDesc(D("city-borders"))
                    .WithArgs(parsers.OptionalWord("state"))
                    .HandleWith(SelectionCommand.Borders)
                .EndSub()
                .BeginSub("wand")
                    .WithDesc(D("city-wand"))
                    .HandleWith(SelectionCommand.GiveWand)
                .EndSub()
                .BeginSub("sel")
                    .WithDesc(D("city-sel"))
                    .HandleWith(SelectionCommand.Info)
                    .BeginSub("pos1")
                        .WithDesc(D("city-sel-pos1"))
                        .HandleWith(args => SelectionCommand.SetCorner(args, 1))
                    .EndSub()
                    .BeginSub("pos2")
                        .WithDesc(D("city-sel-pos2"))
                        .HandleWith(args => SelectionCommand.SetCorner(args, 2))
                    .EndSub()
                    .BeginSub("grow")
                        .WithDesc(D("city-sel-grow"))
                        .WithArgs(parsers.WordRange("direction", Codes.Directions), parsers.Int("blocks"))
                        .HandleWith(args => SelectionCommand.Grow(args, 1))
                    .EndSub()
                    .BeginSub("shrink")
                        .WithDesc(D("city-sel-shrink"))
                        .WithArgs(parsers.WordRange("direction", Codes.Directions), parsers.Int("blocks"))
                        .HandleWith(args => SelectionCommand.Grow(args, -1))
                    .EndSub()
                    .BeginSub("show")
                        .WithDesc(D("city-sel-show"))
                        .HandleWith(args => SelectionCommand.Show(args, true))
                    .EndSub()
                    .BeginSub("hide")
                        .WithDesc(D("city-sel-hide"))
                        .HandleWith(args => SelectionCommand.Show(args, false))
                    .EndSub()
                    .BeginSub("clear")
                        .WithDesc(D("city-sel-clear"))
                        .HandleWith(SelectionCommand.Clear)
                    .EndSub()
                .EndSub();
        }

        /// <summary>
        /// Moving money by command only makes sense with a virtual economy; with bank chests coins
        /// are moved at the chest. Boat sharing is set from the boat window.
        /// </summary>
        public static void RegisterRunGame(ICoreServerAPI sapi, CommandArgumentParsers parsers, string name)
        {
            IChatCommand city = sapi.ChatCommands.Get(name);
            if (city == null) return;
            if (canclaimsextended.economyProvider.SupportsRemoteCoinTransfer)
            {
                city
                    .BeginSub("deposit")
                        .WithDesc(D("city-deposit"))
                        .WithArgs(parsers.OptionalInt("amount"))
                        .HandleWith(CityCommandMoney.Deposit)
                    .EndSub()
                    .BeginSub("withdraw")
                        .WithDesc(D("city-withdraw"))
                        .WithPreCondition(args => BaseCommand.RequirePermission(args, EnumPlayerPermissions.CITY_WITHDRAW_MONEY))
                        .WithArgs(parsers.Int("amount"))
                        .HandleWith(CityCommandMoney.Withdraw)
                    .EndSub();
            }
            city
                .BeginSub("boatshare")
                    .WithDesc(D("city-boatshare"))
                    .WithArgs(parsers.Word("boatId"), parsers.WordRange("mode", "personal", "city"))
                    .HandleWith(part.BoatShare.SetMode)
                .EndSub();
        }
    }
